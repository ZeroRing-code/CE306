BEGIN;

CREATE TABLE IF NOT EXISTS wallets (
    user_id BIGINT PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO wallets (user_id)
SELECT user_id FROM users
ON CONFLICT (user_id) DO NOTHING;

CREATE OR REPLACE FUNCTION create_user_wallet()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO wallets (user_id)
    VALUES (NEW.user_id)
    ON CONFLICT (user_id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_create_wallet ON users;
CREATE TRIGGER users_create_wallet
AFTER INSERT ON users
FOR EACH ROW EXECUTE FUNCTION create_user_wallet();

CREATE TABLE IF NOT EXISTS wallet_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    type VARCHAR(32) NOT NULL CHECK (type IN (
        'top_up', 'purchase', 'refund', 'admin_credit', 'admin_debit',
        'creator_earning', 'platform_fee', 'failed'
    )),
    amount BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN (
        'success', 'failed', 'refunded', 'cancelled'
    )),
    idempotency_key UUID,
    reference_id BIGINT,
    reference_key UUID,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE wallet_transactions
    DROP CONSTRAINT IF EXISTS wallet_transactions_type_check,
    DROP CONSTRAINT IF EXISTS wallet_transactions_status_check;

ALTER TABLE wallet_transactions
    ADD CONSTRAINT wallet_transactions_type_check CHECK (type IN (
        'top_up', 'purchase', 'refund', 'admin_credit', 'admin_debit',
        'creator_earning', 'platform_fee', 'failed'
    )),
    ADD CONSTRAINT wallet_transactions_status_check CHECK (status IN (
        'success', 'failed', 'refunded', 'cancelled'
    ));

CREATE UNIQUE INDEX IF NOT EXISTS wallet_transactions_user_idempotency
    ON wallet_transactions (user_id, idempotency_key)
    WHERE idempotency_key IS NOT NULL AND user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS wallet_transactions_user_created
    ON wallet_transactions (user_id, created_at DESC, transaction_id DESC);
CREATE INDEX IF NOT EXISTS wallet_transactions_reference
    ON wallet_transactions (reference_key)
    WHERE reference_key IS NOT NULL;

CREATE TABLE IF NOT EXISTS chapter_unlocks (
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    chapter_id BIGINT NOT NULL REFERENCES chapters(chapter_id) ON DELETE CASCADE,
    transaction_id BIGINT NOT NULL REFERENCES wallet_transactions(transaction_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, chapter_id)
);

ALTER TABLE chapters
    ADD COLUMN IF NOT EXISTS is_paid BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS price INTEGER NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chapters_paid_price_check'
          AND conrelid = 'chapters'::regclass
    ) THEN
        ALTER TABLE chapters
            ADD CONSTRAINT chapters_paid_price_check
            CHECK (price >= 0 AND (is_paid = FALSE OR price > 0));
    END IF;
END;
$$;

ALTER TABLE notifications
    ADD COLUMN IF NOT EXISTS category VARCHAR(20) NOT NULL DEFAULT 'engagement',
    ADD COLUMN IF NOT EXISTS metadata JSONB NOT NULL DEFAULT '{}'::jsonb;

ALTER TABLE notifications
    DROP CONSTRAINT IF EXISTS notifications_type_check,
    DROP CONSTRAINT IF EXISTS notifications_category_check;

ALTER TABLE notifications
    ADD CONSTRAINT notifications_type_check CHECK (type IN (
        'new_novel', 'new_chapter', 'comment', 'comment_reply', 'mention',
        'first_comments', 'follow', 'review', 'like', 'novel_status',
        'transaction', 'system'
    )),
    ADD CONSTRAINT notifications_category_check CHECK (category IN (
        'system', 'account', 'novel', 'engagement', 'transaction'
    ));

UPDATE notifications
SET category = CASE
    WHEN type IN ('new_novel', 'new_chapter', 'novel_status') THEN 'novel'
    WHEN type = 'transaction' THEN 'transaction'
    WHEN type = 'system' THEN 'system'
    WHEN type = 'comment' THEN 'engagement'
    ELSE 'engagement'
END
WHERE category = 'engagement';

CREATE INDEX IF NOT EXISTS idx_notifications_user_category_created
    ON notifications (user_id, category, created_at DESC, notification_id DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_user_read_created
    ON notifications (user_id, is_read, created_at DESC, notification_id DESC);

COMMIT;
